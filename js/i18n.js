let current = localStorage.getItem('sv:lang') || 'en';
if (!LANGS.some((l) => l.code === current)) current = 'en';

export function getLang() { return current; }

export function tmdbLang() {
  const l = LANGS.find((x) => x.code === current);
  return l ? l.tmdb : 'en-US';
}

export function langMeta(code = current) { return LANGS.find((x) => x.code === code); }

export function isRtl(code = current) { return !!langMeta(code)?.rtl; }

/** Which keys every pack must cover (everything outside LONG_FORM) */
export const CORE_KEYS = Object.keys(DICT.en).filter((k) => !LONG_FORM.has(k));

/** % of CORE keys a pack covers — shown in the language menu */
export function coverage(code) {
  const pack = DICT[code];
  if (!pack) return 0;
  const have = CORE_KEYS.filter((k) => typeof pack[k] === 'string' && pack[k].length > 0).length;
  return Math.round((have / CORE_KEYS.length) * 100);
}

export function t(key) {
  return (DICT[current] && DICT[current][key]) || DICT.en[key] || key;
}

/** Apply translations to every [data-i18n] node; supports placeholder attr.
    Also mirrors the document for RTL languages (Arabic). */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPh));
  });
  document.documentElement.lang = current;
  document.documentElement.dir = isRtl() ? 'rtl' : 'ltr';
}

/** Switch language and notify the app (re-renders live data) */
export function setLang(lang) {
  if (!LANGS.some((l) => l.code === lang)) return;
  current = lang;
  localStorage.setItem('sv:lang', lang);
  applyI18n();
  window.dispatchEvent(new CustomEvent('sv:langchange', { detail: { lang } }));
}
