function detect() {
  const stored = localStorage.getItem(LANG_KEY);
  if (stored && LANGS.some((l) => l.code === stored)) return stored;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return LANGS.some((l) => l.code === nav) ? nav : 'en';
}

export function getLang() {
  if (!current) current = detect();
  return current;
}

export function langMeta(code = getLang()) {
  return LANGS.find((l) => l.code === code) || LANGS[0];
}

export function tmdbLang(code = getLang()) {
  return langMeta(code).tmdb;
}

export function isRTL(code = getLang()) {
  return langMeta(code).dir === 'rtl';
}

/** Translate a key, with {placeholder} interpolation and EN fallback. */
export function t(key, vars) {
  const dict = DICTS[getLang()] || EN;
  let str = dict[key] ?? EN[key] ?? key;
  if (vars && typeof str === 'string') {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  }
  return str;
}

/** Re-label every [data-i18n] / [data-i18n-ph] / [data-i18n-title] node. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.documentElement.lang = getLang();
  document.documentElement.dir = isRTL() ? 'rtl' : 'ltr';
}

export function setLang(code) {
  if (!LANGS.some((l) => l.code === code)) code = 'en';
  current = code;
  localStorage.setItem(LANG_KEY, code);
  applyI18n();
  window.dispatchEvent(new CustomEvent('sv:langchange', { detail: { lang: code, tmdb: tmdbLang(code) } }));
}

/** Human label for an ISO 639-1 code used by the library language filter. */
const ISO_LABELS = {
  en: 'English', id: 'Indonesian', ko: 'Korean', ja: 'Japanese', es: 'Spanish', fr: 'French',
  de: 'German', hi: 'Hindi', zh: 'Chinese', pt: 'Portuguese', ru: 'Russian', tr: 'Turkish',
  it: 'Italian', th: 'Thai', ar: 'Arabic',
};
export function langLabel(code) {
  if (!code) return t('movies.filter.any');
  return ISO_LABELS[code] || code.toUpperCase();
}
