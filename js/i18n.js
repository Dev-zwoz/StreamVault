/** How much of the English master a pack covers (0-100). */
export function langCoverage(code) {
  if (!code || code === 'en' || code === 'id') return 100;
  const pack = PACK_KEYS[code];
  if (!pack) return 100;
  return Math.round((pack.size / Object.keys(EN).length) * 100);
}

